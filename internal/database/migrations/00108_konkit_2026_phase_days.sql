INSERT INTO schedule_phase_days (schedule_id, day, phase)
SELECT ps.id, sheet.day::date, sheet.phase
FROM sheet
JOIN regencies r ON upper(r.name) = sheet.regency_name
JOIN program_schedules ps ON ps.regency_id = r.id AND ps.status <> 'cancelled'
JOIN programs p ON p.id = ps.program_id AND p.code = 'KONKIT-2026'
WHERE NOT EXISTS (SELECT 1 FROM schedule_phase_days d WHERE d.schedule_id = ps.id)
ON CONFLICT DO NOTHING;

